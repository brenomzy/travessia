// Builds src/styles/tokens.css and src/tokens/tokens.ts from src/tokens/tokens.json (SPEC §5.5.2, D14).
// No dependencies. Run with `npm run tokens` (Node strips the types).
// Fails if a semantic text colour drops below WCAG AA on its background.
import { readFileSync, writeFileSync } from 'node:fs';

type Json = Record<string, any>;
const root = new URL('../', import.meta.url);
const src: Json = JSON.parse(readFileSync(new URL('src/tokens/tokens.json', root), 'utf8'));

const vwMin: number = src.viewport.min.$value;
const vwMax: number = src.viewport.max.$value;
const rem = (px: number) => `${+(px / 16).toFixed(4)}rem`;
const kebab = (path: string[]) => path.join('-');
const isToken = (n: Json) => n && typeof n === 'object' && '$value' in n;

/** Walks every token under a group, skipping $-keys. */
function walk(node: Json, path: string[], fn: (path: string[], token: Json) => void) {
  for (const [key, child] of Object.entries(node)) {
    if (key.startsWith('$')) continue;
    if (isToken(child)) fn([...path, key], child);
    else if (child && typeof child === 'object') walk(child, [...path, key], fn);
  }
}

/** "{palette.agua.500}" → node in the JSON */
function lookup(ref: string): Json {
  const node = ref.slice(1, -1).split('.').reduce((n: Json, k) => n?.[k], src);
  if (!isToken(node)) throw new Error(`Unknown token reference ${ref}`);
  return node;
}
const isRef = (v: unknown): v is string => typeof v === 'string' && /^\{.+\}$/.test(v);
/** Resolves aliases to a raw value (for tokens.ts and contrast checks). */
const resolve = (v: any): any => (isRef(v) ? resolve(lookup(v).$value) : v);
/** "{palette.agua.500}" → "var(--agua-500)" (palette names drop the "palette" prefix). */
const refVar = (ref: string) => {
  const parts = ref.slice(1, -1).split('.');
  return `var(--${kebab(parts[0] === 'palette' ? parts.slice(1) : parts)})`;
};

function fluid({ min, max }: { min: number; max: number }) {
  if (min === max) return rem(min);
  const slope = (max - min) / (vwMax - vwMin);
  const intercept = min - slope * vwMin;
  return `clamp(${rem(min)}, ${rem(intercept)} + ${+(slope * 100).toFixed(4)}vw, ${rem(max)})`;
}

function cssValue(token: Json): string {
  const v = token.$value;
  if (isRef(v)) return refVar(v);
  switch (token.$type) {
    case 'fluid': return fluid(v);
    case 'dimension': return typeof v === 'number' ? (v === 999 ? '999px' : rem(v)) : v;
    case 'duration': return `${v}ms`;
    case 'cubicBezier': return `cubic-bezier(${v.join(', ')})`;
    case 'easing': return v; // a CSS easing string, e.g. linear(…) for springs
    default: return String(v);
  }
}

// ---------- CSS ----------
const lines: string[] = [];
const decl = (name: string, value: string) => lines.push(`  --${name}: ${value};`);

lines.push('/* Generated by scripts/build-tokens.ts from src/tokens/tokens.json. Do not edit. */', ':root {');
walk(src.palette, [], (p, t) => decl(kebab(p), cssValue(t)));
walk(src.color, ['color'], (p, t) => decl(kebab(p), cssValue(t)));
walk(src.font, ['font'], (p, t) => decl(kebab(p.filter((k) => k !== 'family')), cssValue(t)));
walk(src.text, ['text'], (p, t) => {
  decl(kebab(p), cssValue(t));
  decl(kebab(['leading', ...p.slice(1)]), String(t.leading));
});
walk(src.space, ['space'], (p, t) => decl(kebab(p), cssValue(t)));
walk(src.size, ['size'], (p, t) => decl(kebab(p), cssValue(t)));
walk(src.radius, ['radius'], (p, t) => decl(kebab(p), cssValue(t)));
walk(src.shadow, ['shadow'], (p, t) => decl(kebab(p), cssValue(t)));
walk(src.opacity, ['opacity'], (p, t) => decl(kebab(p), cssValue(t)));
walk(src.scale, ['scale'], (p, t) => decl(kebab(p), cssValue(t)));
// Motion tokens drop the "motion" prefix: --duration-fast, --ease-base, --spring-crit, --reveal-blur.
// Motion-style spring configs ($type "spring") are TS only.
walk(src.motion, [], (p, t) => {
  if (t.$type !== 'spring') decl(kebab(p.slice(-2)), cssValue(t));
});
lines.push('}', '');

const themeNames = Object.keys(src.themes).filter((k) => !k.startsWith('$'));
for (const theme of themeNames) {
  const selector = theme === 'light' ? ':root,\n[data-theme="light"]' : `[data-theme="${theme}"]`;
  lines.push(`${selector} {`);
  for (const [name, ref] of Object.entries<string>(src.themes[theme])) decl(name.replaceAll('.', '-'), refVar(ref));
  lines.push('  color: var(--color-text-base);', '}', '');
}
// The seam turns horizontal below the laptop breakpoint, so a block can take a different theme there.
// data-theme-laptop="…" applies a theme from the laptop breakpoint up, data-theme-desktop="…" from the desktop
// breakpoint up (later in the file, so it wins where both match).
for (const bp of ['laptop', 'desktop'] as const) {
  lines.push(`@media (width >= ${src.breakpoint[bp].$value / 16}rem) {`);
  for (const theme of themeNames) {
    lines.push(`  [data-theme-${bp}="${theme}"] {`);
    for (const [name, ref] of Object.entries<string>(src.themes[theme])) lines.push(`    --${name.replaceAll('.', '-')}: ${refVar(ref)};`);
    lines.push('    color: var(--color-text-base);', '  }');
  }
  lines.push('}', '');
}
writeFileSync(new URL('src/styles/tokens.css', root), lines.join('\n'));

// ---------- TS ----------
function toObject(node: Json, convert: (t: Json) => any): Json {
  const out: Json = {};
  for (const [key, child] of Object.entries(node)) {
    if (key.startsWith('$')) continue;
    out[key] = isToken(child) ? convert(child) : toObject(child, convert);
  }
  return out;
}
const raw = (t: Json) => {
  const v = resolve(t.$value);
  if (t.$type === 'duration') return v / 1000; // seconds, for Motion
  return v;
};
const themes = Object.fromEntries(
  themeNames.map((th) => [th, Object.fromEntries(Object.entries<string>(src.themes[th]).map(([k, r]) => [k, resolve(r)]))]),
);
const ts = {
  palette: toObject(src.palette, raw),
  color: toObject(src.color, raw),
  themes,
  font: toObject(src.font, raw),
  text: toObject(src.text, (t) => ({ ...t.$value, leading: t.leading })),
  space: toObject(src.space, raw),
  size: toObject(src.size, raw),
  breakpoint: toObject(src.breakpoint, raw),
  radius: toObject(src.radius, raw),
  shadow: toObject(src.shadow, raw),
  opacity: toObject(src.opacity, raw),
  scale: toObject(src.scale, raw),
};
const motion = toObject(src.motion, raw);
// Motion is its own export so client scripts can import it without bundling every other token.
const tokensJson = JSON.stringify(ts, null, 2).replace(/\n}$/, ',\n  "motion": motion\n}');
writeFileSync(
  new URL('src/tokens/tokens.ts', root),
  `// Generated by scripts/build-tokens.ts from src/tokens/tokens.json. Do not edit.
// Colours are resolved hex values; durations are in seconds; easings are cubic-bezier arrays.
export const motion = ${JSON.stringify(motion, null, 2)} as const;

export const tokens = ${tokensJson} as const;

export type Tokens = typeof tokens;

/** "color.accent.primary" → "var(--color-accent-primary)" */
export const cssVar = (dotted: string) => \`var(--\${dotted.replaceAll('.', '-')})\`;
`,
);

// ---------- Contrast (WCAG AA) ----------
function luminance(hex: string) {
  const [r, g, b] = [1, 3, 5].map((i) => parseInt(hex.slice(i, i + 2), 16) / 255).map((c) => (c <= 0.04045 ? c / 12.92 : ((c + 0.055) / 1.055) ** 2.4));
  return 0.2126 * r + 0.7152 * g + 0.0722 * b;
}
function ratio(a: string, b: string) {
  const [l1, l2] = [luminance(a), luminance(b)].sort((x, y) => y - x);
  return (l1 + 0.05) / (l2 + 0.05);
}
const failures: string[] = [];
const check = (label: string, fg: string, bg: string, min = 4.5) => {
  const r = ratio(fg, bg);
  if (r < min) failures.push(`${label}: ${r.toFixed(2)}:1 (needs ${min}:1)`);
};
for (const th of themeNames) {
  const t = themes[th];
  for (const role of ['color.text.base', 'color.text.muted', 'color.text.subtle', 'color.text.quiet', 'color.text.highlight', 'color.link']) {
    check(`${th} ${role} on bg`, t[role], t['color.bg.base']);
  }
  check(`${th} placeholder on field`, t['color.field.placeholder'], t['color.field.bg']);
  check(`${th} chip text on chip`, t['color.chip.text'], t['color.chip.bg']);
}
check('on-accent on accent.primary', ts.color['on-accent'], ts.color.accent.primary);
check('banner text on banner bg', ts.color.banner.text, ts.color.banner.bg);

if (failures.length) {
  console.error(`Contrast check failed:\n  ${failures.join('\n  ')}`);
  process.exit(1);
}
console.log(`tokens: wrote src/styles/tokens.css and src/tokens/tokens.ts; ${themeNames.length} themes pass WCAG AA.`);
